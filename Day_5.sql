USE sql7challenge;

-- Calculate the total sales value from non-cancelled orders.
SELECT SUM(order_items.quantity * order_items.unit_price) AS total_sales
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
WHERE orders.status <> "Cancelled";


-- Identify which product categories generate the most sales.
SELECT products.category, SUM(order_items.quantity * order_items.unit_price) AS sales_value
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
JOIN products ON products.product_id = order_items.product_id
WHERE orders.status <> "Cancelled"
GROUP BY products.category
ORDER BY sales_value DESC;


-- Find the 10 products generating the most sales value.
SELECT products.product_id, products.product_name, SUM(order_items.quantity * order_items.unit_price) AS sales_value
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
JOIN products ON products.product_id = order_items.product_id
WHERE orders.status <> "Cancelled"
GROUP BY products.product_id, products.product_name
ORDER BY sales_value DESC
LIMIT 10;


-- Calculate the total quantity sold for each product.
SELECT products.product_id, products.product_name, SUM(order_items.quantity) AS total_quantity_sold
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
JOIN products ON products.product_id = order_items.product_id
WHERE orders.status <> "Cancelled"
GROUP BY products.product_id, products.product_name
ORDER BY total_quantity_sold DESC;


-- Calculate the average product selling price in each category.
SELECT products.category, ROUND(AVG(products.price), 3) AS avg_selling_price
FROM products
GROUP BY products.category
ORDER BY avg_selling_price DESC;


-- Calculate sales value generated by each sales channel.
SELECT orders.channel, ROUND(SUM(order_items.quantity * order_items.unit_price), 2) AS sales_value
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
WHERE orders.status <> "Cancelled"
GROUP BY orders.channel
ORDER BY sales_value DESC;


-- Calculate estimated profit by product using the product cost and item selling price.
SELECT products.product_id, products.product_name, ROUND(SUM(order_items.quantity * (order_items.unit_price - products.cost)), 2) AS estimated_profit
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
JOIN products ON products.product_id = order_items.product_id
WHERE orders.status <> "Cancelled"
GROUP BY products.product_id, products.product_name
ORDER BY estimated_profit DESC;


-- Find the five categories with the highest total quantity sold.
SELECT products.category, SUM(order_items.quantity) AS total_quantity_sold
FROM orders
JOIN order_items ON order_items.order_id = orders.order_id
JOIN products ON products.product_id = order_items.product_id
WHERE orders.status <> "Cancelled"
GROUP BY products.category
ORDER BY total_quantity_sold DESC
LIMIT 5;



-- Insights
-- Sports & Fitness leads (11.0M) and Electronics trails (8.0M). Average price follows the same order, from 4,939 for Sports down to 3,381 for Electronics.

-- Volume doesn’t drive revenue. Beauty sells the most units (2,406) but ranks 5th in revenue. Sports & Fitness sells the fewest units but ranks 1st.

-- No single product dominates. The top 10 of 150 products make up only 13.9% of sales, and the #1 product, Storage Box 26, is 1.6%.

-- Revenue rank is not profit rank. Power Bank 13 is #5 in revenue but #29 in profit, with a margin of only about 40%.

-- Cancellations remove about 8% of order value, and channels are close. Social Commerce leads at 15.4M (26.7%), just ahead of Website at 15.0M (26.0%).